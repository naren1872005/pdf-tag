from typing import List, Dict, Any
from graph.document_graph import DocumentGraph

class GraphAction:
    def __init__(self, action_type: str, target_uuid: str, payload: Dict[str, Any], rule_name: str):
        self.action_type = action_type # e.g. "UPDATE_TAG", "DEMOTE_HEADING"
        self.target_uuid = target_uuid
        self.payload = payload
        self.rule_name = rule_name

class ActionQueue:
    """
    Collects actions generated by Rule plugins and applies them to the Graph safely.
    """
    def __init__(self):
        self.actions: List[GraphAction] = []
        self.reports: List[Dict[str, Any]] = []
        
    def add_action(self, action: GraphAction):
        self.actions.append(action)
        
    def apply_all(self, graph: DocumentGraph):
        for action in self.actions:
            node = graph.get_node(action.target_uuid)
            if not node: continue
            
            # Record state before
            before_state = {
                "pdf_tag": node.semantic.get("pdf_tag"),
                "semantic_type": node.semantic.get("type")
            }
            
            if action.action_type == "UPDATE_TAG":
                node.semantic["pdf_tag"] = action.payload.get("new_tag")
                node.add_history(f"{action.rule_name} Rule Applied: Changed tag to {node.semantic['pdf_tag']}")
            elif action.action_type == "UPDATE_SEMANTICS":
                node.semantic["type"] = action.payload.get("new_type")
                node.add_history(f"{action.rule_name} Rule Applied: Changed semantic type to {node.semantic['type']}")
            elif action.action_type == "ADD_INLINE_LINKS":
                node.analysis.setdefault("inline_links", []).extend(action.payload.get("links", []))
                node.add_history(f"{action.rule_name} Rule Applied: Attached inline links metadata")
                
            # Log rule report
            self.reports.append({
                "rule": action.rule_name,
                "before": before_state,
                "after": {
                    "pdf_tag": node.semantic.get("pdf_tag"),
                    "semantic_type": node.semantic.get("type")
                },
                "modified_nodes": [node.uuid]
            })
            
        self.actions.clear()
